package com.example.tiktokai

object LocalContentGenerator {
    fun generate(topic:String):BackendApiV16.GeneratedContent {
        val clean=topic.trim().replace(Regex("\\s+")," ")
        val variant=Math.floorMod(clean.hashCode(),4)
        val hook=when(variant) {
            0 -> "تخيل أن هذا حدث فجأة… كيف ستتغير حياتنا خلال الساعات الأولى؟"
            1 -> "هذا السؤال يبدو بسيطًا، لكن نتيجته قد تغيّر تفاصيل يومنا بالكامل."
            2 -> "ماذا لو استيقظنا غدًا ووجدنا أن هذا السيناريو أصبح حقيقة؟"
            else -> "هناك نتيجة أولى نتوقعها جميعًا… لكن النتيجة التالية قد تفاجئك."
        }
        val scenes=when(variant) {
            0 -> listOf(
                "نبدأ من اللحظة الأولى: $clean",
                "خلال الدقائق الأولى سيحاول الناس فهم ما يحدث والبحث عن بدائل سريعة.",
                "بعد ساعات ستظهر التأثيرات على العمل والتواصل والخدمات اليومية.",
                "ثم تبدأ نتائج أقل وضوحًا بالظهور على العادات والاقتصاد وطريقة اتخاذ القرارات.",
                "في النهاية يبقى السؤال: ما أول شيء ستفعله أنت في هذا السيناريو؟"
            )
            1 -> listOf(
                "السؤال الرئيسي هو: $clean",
                "أول تأثير سيكون مباشرًا على الأشياء التي نعتمد عليها كل يوم.",
                "بعد ذلك ستضطر المؤسسات والأفراد إلى تغيير خططهم بسرعة.",
                "مع مرور الوقت تظهر حلول جديدة، لكن معها مشكلات لم تكن متوقعة.",
                "لو كنت داخل هذا الموقف، أي حل ستختار أولًا؟"
            )
            2 -> listOf(
                "تخيل المشهد: $clean",
                "في البداية سيظن كثيرون أن الأمر مؤقت ولن يغيّر شيئًا كبيرًا.",
                "لكن مع مرور الساعات تبدأ التفاصيل الصغيرة بالتراكم وتصبح مؤثرة.",
                "هنا تظهر الفجوة بين من استعد مسبقًا ومن يعتمد على الوضع المعتاد.",
                "برأيك، هل ستكون النتيجة إيجابية أم سلبية على المدى القصير؟"
            )
            else -> listOf(
                "لنبدأ بالسؤال: $clean",
                "النتيجة الأولى واضحة، لكن تأثيرها الحقيقي يبدأ من التغيّر في سلوك الناس.",
                "بعدها تنتقل التأثيرات إلى الخدمات والعمل والقرارات اليومية.",
                "المفاجأة أن بعض الناس قد يجدون فرصًا جديدة وسط المشكلة.",
                "اكتب في التعليقات ما النتيجة التي تتوقعها ولم نذكرها."
            )
        }
        val words=clean.split(Regex("[^\\p{L}\\p{N}]+"))
            .filter { it.length>=3 }
            .distinct()
            .take(3)
        val tags=buildList {
            add("#معلومات")
            add("#ذكاء_اصطناعي")
            words.forEach { add("#"+it.replace(" ","_")) }
            add("#TikTok")
        }.distinct().take(7)

        val prompts=(listOf(hook)+scenes).mapIndexed { index,text ->
            "Cinematic vertical 9:16 visual, realistic, dramatic lighting, no text, scene "+(index+1)+", topic: "+clean+", concept: "+text
        }

        return BackendApiV16.GeneratedContent(
            title=clean,
            hook=hook,
            description="سيناريو قصير يشرح بصورة مبسطة ماذا قد يحدث إذا تحقق هذا الاحتمال: $clean",
            hashtags=tags,
            scenes=scenes,
            visualPrompts=prompts
        )
    }
}
